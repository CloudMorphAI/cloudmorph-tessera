def _emit_mixed_events(sink: SqliteSink, tenant_id: str, n_each: int = 2) -> AuditEmitter:
    """Emit a realistic mix of decision events (allow/block/require_approval/log_only)."""
    emitter = AuditEmitter(tenant_id=tenant_id, sinks=[sink])
    tools = ["aws.s3.getObject", "aws.s3.deleteBucket", "aws.ec2.terminateInstances"]
    for i in range(n_each):
        emitter.emit(
            "decision",
            payload={
                "mode": "enforcement",
                "decision": "allow",
                "policy_id": "policy-allow-reads",
                "reason": "read-only call permitted",
                "canonical_tool_name": tools[0],
                "tool_call": {"name": tools[0], "arguments": {"i": i}},
            },
        )
        emitter.emit(
            "decision",
            payload={
                "mode": "enforcement",
                "decision": "block",
                "policy_id": "policy-block-deletes",
                "reason": "destructive action blocked",
                "canonical_tool_name": tools[1],
                "tool_call": {"name": tools[1], "arguments": {"i": i}},
            },
        )
        emitter.emit(
            "decision",
            payload={
                "mode": "enforcement",
                "decision": "require_approval",
                "policy_id": "policy-require-approval",
                "reason": "approval_required: high blast radius",
                "canonical_tool_name": tools[2],
                "tool_call": {"name": tools[2], "arguments": {"i": i}},
            },
        )
        emitter.emit(
            "decision",
            payload={
                "mode": "observation",
                "decision": "log_only",
                "policy_id": None,
                "reason": None,
                "canonical_tool_name": tools[0],
                "tool_call": {"name": tools[0], "arguments": {"i": i}},
            },
        )
    return emitter


def _flip_one_char(text: str, marker: str) -> str:
    """Flip a single character right after `marker` in `text` (a genuine one-byte tamper)."""
    idx = text.index(marker) + len(marker)
    ch = text[idx]
    replacement = "1" if ch != "1" else "2"
    return text[:idx] + replacement + text[idx + 1 :]


