@pytest.mark.parametrize(
    "value",
    [
        "2026-07-01",
        "2026-07-01T00:00:00Z",
        "2026-07-01T00:00:00.123456Z",
        "2026-07-01T00:00:00+00:00",
    ],
)
def test_parse_ts_accepts_common_formats(value: str) -> None:
    dt = parse_ts(value)
    assert dt.year == 2026
    assert dt.month == 7
    assert dt.day == 1


def test_format_ts_matches_emitter_format() -> None:
    dt = parse_ts("2026-07-01T12:34:56.789000Z")
    formatted = format_ts(dt)
    assert formatted.endswith("Z")
    # Round-trips back to an equivalent instant.
    assert parse_ts(formatted) == dt


