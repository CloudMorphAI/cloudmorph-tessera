def test_export_and_verify_large_synthetic_chain_perf(
    tmp_path: Path, signing_key_path: Path
) -> None:
    """A few thousand synthetic events export + verify in reasonable time."""
    sink = SqliteSink(path=tmp_path / "audit.db")
    out_dir = tmp_path / "bundle_large"
    try:
        _emit_mixed_events(sink, "tnt_perf", n_each=625)  # 625*4 = 2500 events

        start = time.perf_counter()
        manifest = export_evidence_bundle(
            sink, scope="tnt_perf", from_ts=None, to_ts=None, out_dir=out_dir
        )
        export_elapsed = time.perf_counter() - start
    finally:
        sink.close()

    assert manifest["event_counts"]["total"] == 2500

    start = time.perf_counter()
