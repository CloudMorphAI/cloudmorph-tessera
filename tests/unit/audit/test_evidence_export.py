def test_verify_bundle_dir_detects_single_byte_tamper_at_correct_index(
    tmp_path: Path, signing_key_path: Path
) -> None:
    out_dir = _make_bundle(tmp_path, n_each=3)
    events_path = out_dir / "events.jsonl"
    lines = events_path.read_text(encoding="utf-8").splitlines()
    assert len(lines) == 12

    # Flip one character inside the THIRD event's eventHash — a genuine single-byte tamper.
    lines[2] = _flip_one_char(lines[2], '"eventHash": "')
    events_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    result = verify_bundle_dir(out_dir)
    assert result["ok"] is False
    assert result["first_failure"]["seq"] == 3
    assert result["first_failure"]["kind"] == "hash_mismatch"


def test_verify_bundle_dir_detects_chain_break(tmp_path: Path, signing_key_path: Path) -> None:
    out_dir = _make_bundle(tmp_path, n_each=3)
    events_path = out_dir / "events.jsonl"
    lines = events_path.read_text(encoding="utf-8").splitlines()

    # Rewrite event 5's prevEventHash+eventHash consistently (self-consistent hash,
    # but breaks the link to event 4) — a chain_break rather than a hash_mismatch.
    event = json.loads(lines[4])
    event["prevEventHash"] = "ab" * 32
    digest_input = {**event, "eventHash": "", "signature": ""}
    event["eventHash"] = hashlib.sha256(canonical_json(digest_input)).hexdigest()
    lines[4] = json.dumps(event)
    events_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    result = verify_bundle_dir(out_dir)
    assert result["ok"] is False
    assert result["first_failure"]["seq"] == 5
    assert result["first_failure"]["kind"] == "chain_break"


def test_verify_bundle_dir_detects_signature_tamper(tmp_path: Path, signing_key_path: Path) -> None:
    out_dir = _make_bundle(tmp_path)
    manifest_path = out_dir / "manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    # Corrupt the signature only — chain itself is untouched.
    sig = manifest["signing"]["signature"]
    manifest["signing"]["signature"] = ("A" if sig[0] != "A" else "B") + sig[1:]
    manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")

    result = verify_bundle_dir(out_dir)
    assert result["ok"] is False
    assert result["signature_ok"] is False
    assert result["first_failure"]["kind"] == "signature_invalid"
    # Chain itself was never broken.
    assert result["events_checked"] == 8


def test_verify_bundle_dir_detects_manifest_counts_tamper(
    tmp_path: Path, signing_key_path: Path
) -> None:
    """Patching manifest.json's *displayed* counts (without re-signing, and without
    touching events.jsonl) must still fail verification overall.

    The Ed25519 signature is checked against a payload recomputed from events.jsonl,
    so it still validates (events.jsonl itself is untouched — that's the true source
    signed at export time). But a separate consistency check catches the manifest's
    now-false displayed numbers not matching events.jsonl's actual contents, so a
    human trusting manifest.json alone (without recomputation) isn't misled.
    """
    out_dir = _make_bundle(tmp_path)
    manifest_path = out_dir / "manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    manifest["event_counts"]["block"] = 0  # lie: hide the blocks
    manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")

    result = verify_bundle_dir(out_dir)
    assert result["signature_ok"] is True
    assert result["manifest_consistent"] is False
    assert result["ok"] is False
    assert result["first_failure"]["kind"] == "manifest_mismatch"


